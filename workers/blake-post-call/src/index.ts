// Listing-agent lookup via Anthropic web_search
// =============================================================================
//
// Zillow/Redfin emails carry the brokerage name but rarely the listing agent's
// direct phone/email. Their listing pages have it, but Zillow blocks Worker
// fetches with HTTP 403. So we ask Claude to web-search and extract.
//
// Cost per lookup: ~$0.01-0.03 (Sonnet input + search tool usage).
// Reliability: ~85% — Claude finds the agent block on Zillow / Realtor / brokerage
// site. Returns empty fields when the public web doesn't expose the info.
//
// Called from handleListingEmail when realtor_phone wasn't in the email body.

interface AgentLookupResult {
  agent_name?: string;
  agent_phone?: string;
  agent_email?: string;
  brokerage?: string;
  source?: "claude_web_search";
  raw_response?: string;     // present only on parse failure
  error?: string;            // present only on API error
}

async function lookupListingAgentViaWebSearch(
  env: Env,
  listingUrl: string,
  address: string,
  city?: string,
  state?: string
): Promise<AgentLookupResult> {
  if (!env.ANTHROPIC_API_KEY) return { error: "no_anthropic_key" };

  const locationLine = [address, city, state].filter(Boolean).join(", ");
  const prompt = `You are an APG real-estate operations assistant. Find the listing agent's contact details for this specific property.

Property: ${locationLine}
${listingUrl ? `Listing URL: ${listingUrl}` : ""}

STRATEGY: Public web search results do NOT index the specific listing agent for a given Zillow URL — that data only appears on the actual listing page itself. So:

1. FIRST, use the web_fetch tool to fetch the Zillow listing URL directly (you have access to it; Workers don't but you do). Look for the "Listed by:" / "Listing agent:" / agent contact block on the rendered listing page.
2. If web_fetch returns the listing data, extract: agent name, phone (10-digit), email, brokerage.
3. If web_fetch fails or doesn't have the agent block, FALLBACK to web_search to find the agent via Realtor.com, the brokerage website, or MLS directories using the property address.

Return EXACTLY this JSON object and nothing else — no prose, no code fences, no commentary:
{"agent_name":"...","agent_phone":"...","agent_email":"...","brokerage":"..."}

For any field you cannot find from web_fetch or web_search, use an empty string. Do not invent or guess data.`;

  let res: Response;
  try {
    res = await fetch("https://api.anthropic.com/v1/messages", {
      method: "POST",
      headers: {
        "x-api-key": env.ANTHROPIC_API_KEY,
        "anthropic-version": "2023-06-01",
        "content-type": "application/json",
      },
      body: JSON.stringify({
        model: "claude-sonnet-4-6",
        max_tokens: 1024,
        tools: [
          // web_fetch lets Claude directly retrieve URL contents. Critical for
          // Zillow listing agents — Google doesn't index that data, only the
          // live listing page has it.
          { type: "web_fetch_20250910", name: "web_fetch", max_uses: 3 },
          { type: "web_search_20250305", name: "web_search", max_uses: 3 },
        ],
        messages: [{ role: "user", content: prompt }],
      }),
    });
  } catch (e: any) {
    return { error: `fetch_threw: ${e?.message || String(e)}` };
  }

  if (!res.ok) {
    const errText = await res.text();
    console.warn(`[agent-lookup] anthropic ${res.status}: ${errText.slice(0, 300)}`);
    return { error: `anthropic_${res.status}` };
  }

  const data: any = await res.json();
  let textOutput = "";
  for (const block of data.content || []) {
    if (block.type === "text") textOutput += block.text;
  }

  // The model is instructed to return ONLY a JSON object. Be tolerant of
  // accidental code fences or surrounding whitespace.
  const jsonMatch = textOutput.match(/\{[\s\S]*\}/);
  if (!jsonMatch) {
    return { source: "claude_web_search", raw_response: textOutput.slice(0, 500) };
  }
  let parsed: any = {};
  try {
    parsed = JSON.parse(jsonMatch[0]);
  } catch {
    return { source: "claude_web_search", raw_response: textOutput.slice(0, 500), error: "json_parse" };
  }

  // Normalize phone to E.164 (+1XXXXXXXXXX) if possible
  let phone = String(parsed.agent_phone || "").trim();
  if (phone) {
    const digits = phone.replace(/\D/g, "");
    if (digits.length === 10) phone = `+1${digits}`;
    else if (digits.length === 11 && digits.startsWith("1")) phone = `+${digits}`;
    else if (digits.length < 10) phone = "";   // junk — discard
    else phone = `+${digits}`;
  }

  return {
    source: "claude_web_search",
    agent_name: String(parsed.agent_name || "").trim() || undefined,
    agent_phone: phone || undefined,
    agent_email: String(parsed.agent_email || "").trim() || undefined,
    brokerage: String(parsed.brokerage || "").trim() || undefined,
  };
}

async function handleListingEmailFromHtml(req: Request, env: Env): Promise<Response> {
  let body: any = {};
  try {
    body = await req.json();
  } catch {
    return new Response(JSON.stringify({ ok: false, error: "invalid_json" }), {
      status: 400,
      headers: { "content-type": "application/json" },
    });
  }

  const rawHtml = String(body.raw_html || "");
  const from = String(body.from || "");
  const subject = String(body.subject || "");
  const dryRun = body.dry_run === true || body.dry_run === "true";

  if (!rawHtml) {
    return new Response(
      JSON.stringify({ ok: false, error: "missing_raw_html" }),
      { status: 400, headers: { "content-type": "application/json" } }
    );
  }

  const parsed = parseListingEmail(rawHtml, from, subject);

  // Critical-fields check: must have an address AND an asking price to fire
  // the rest of the pipeline. If either is missing, return 422 with parse
  // result so the user (or n8n) can manually review.
  if (!parsed.property_address || !parsed.asking_price) {
    return new Response(
      JSON.stringify({
        ok: false,
        error: "parse_incomplete",
        details: "Could not extract property_address and/or asking_price from this email.",
        parsed,
        from, subject,
        html_excerpt: rawHtml.slice(0, 500),
      }, null, 2),
      { status: 422, headers: { "content-type": "application/json" } }
    );
  }

  // State allowlist: only NJ + PA listings fire the full pipeline. Anything
  // else gets parsed + returned but no SMS / Slack / GHL side effects (saves
  // Twilio + GHL cost on out-of-buy-box alerts).
  const inBuyBox = !!parsed.state && NJ_PA_ALLOWED_STATES.has(parsed.state);
  if (!inBuyBox && parsed.state) {
    // Notify Slack so we still see it, then return early.
    const note = `:no_entry: *Out-of-buy-box listing skipped* — ${parsed.property_address}, ${parsed.city || "?"}, ${parsed.state} (buy box = NJ + PA only)`;
    await postSlackMessage(env, SLACK_LISTINGS_CHANNEL, note).catch(() => {});
    return new Response(
      JSON.stringify({
        ok: true,
        skipped_reason: "out_of_buy_box",
        buy_box: ["NJ", "PA"],
        parsed,
      }, null, 2),
      { status: 200, headers: { "content-type": "application/json" } }
    );
  }

  // Property-type filter — buy box is single-family + multi-family + townhouse.
  // BLOCK: condo / condominium / co-op / apartment / manufactured / mobile /
  // trailer (per user direction 2026-05-24). Multi-family and townhouses
  // were previously blocked; now allowed.
  const blockedPropertyTypes = [
    "condo", "condominium",
    "co-op", "co op", "coop",
    "apartment building", "apartments",
    "manufactured home", "mobile home", "trailer home",
  ];
  const haystack = `${rawHtml} ${subject || ""}`.toLowerCase();
  const matchedBlocked = blockedPropertyTypes.find((kw) => haystack.includes(kw));
  if (matchedBlocked) {
    const note = `:no_entry: *Out-of-buy-box property type skipped* — ${parsed.property_address}, ${parsed.city || "?"}, ${parsed.state || "?"} (matched "${matchedBlocked}"; buy box = SFR + multi + townhouse only)`;
    await postSlackMessage(env, SLACK_LISTINGS_CHANNEL, note).catch(() => {});
    return new Response(
      JSON.stringify({
        ok: true,
        skipped_reason: "blocked_property_type",
        matched_keyword: matchedBlocked,
        buy_box: "sfr_multi_townhouse_only",
        parsed,
      }, null, 2),
      { status: 200, headers: { "content-type": "application/json" } }
    );
  }

  if (dryRun) {
    return new Response(
      JSON.stringify({ ok: true, dry_run: true, parsed }, null, 2),
      { status: 200, headers: { "content-type": "application/json" } }
    );
  }

  // Forward to the existing handler by re-invoking with a synthetic Request.
  const forwarded = new Request("https://internal/listing-email", {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify(parsed),
  });
  return handleListingEmail(forwarded, env);
}

// --- Twilio DTMF injection on live call ---
// Used when a GHL number forwards an inbound call to Blake. GHL plays a
// "Press 1 to connect" whisper prompt that requires DTMF acknowledgement.
// Blake (AI) can't press a key with his voice, so we POST to Twilio's
// Calls API to inject TwiML <Play digits="1"/> on the live call SID,
// which sends the DTMF tone GHL needs to bridge the real caller through.
//
// Twilio docs: https://www.twilio.com/docs/voice/api/call-resource#update-a-call-resource
//   Modifying an in-progress call by setting Twiml param resets the call's
//   instructions mid-flight. Twilio plays the digits, then resumes whatever
//   it was doing (in our case, the ElevenLabs media stream).
async function injectDtmfOnTwilioCall(
  env: Env,
  callSid: string,
  digits: string
): Promise<{ ok: boolean; status: number; body: string }> {
  if (!env.TWILIO_ACCOUNT_SID || !env.TWILIO_AUTH_TOKEN) {
    return { ok: false, status: 0, body: "twilio_creds_not_bound" };
  }
  const auth = btoa(`${env.TWILIO_ACCOUNT_SID}:${env.TWILIO_AUTH_TOKEN}`);
  const form = new URLSearchParams({
    Twiml: `<Response><Play digits="${digits}"/></Response>`,
  });
  const res = await fetch(
    `https://api.twilio.com/2010-04-01/Accounts/${env.TWILIO_ACCOUNT_SID}/Calls/${callSid}.json`,
    {
      method: "POST",
      headers: {
        Authorization: `Basic ${auth}`,
        "Content-Type": "application/x-www-form-urlencoded",
      },
      body: form.toString(),
    }
  );
  const text = await res.text();
  return { ok: res.ok, status: res.status, body: text.slice(0, 500) };
}

