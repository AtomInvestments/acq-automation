async function fetchWpPageMeta(env: Env, pageId: number): Promise<{
  id: number; modified: string; link: string; title: string; slug: string;
} | null> {
  if (!env.WP_AUTH_HEADER) {
    console.warn("[insights] WP_AUTH_HEADER not configured");
    return null;
  }
  const res = await fetch(
    `${WP_REST_BASE}/pages/${pageId}?_fields=id,modified,link,title,slug`,
    { headers: { Authorization: env.WP_AUTH_HEADER } }
  );
  if (!res.ok) return null;
  const p: any = await res.json();
  return {
    id: p.id,
    modified: p.modified,
    link: p.link,
    title: p.title?.rendered || "",
    slug: p.slug || "",
  };
}

async function captureAndStoreSnapshot(
  env: Env,
  pageId: number,
  pageUrl: string,
  modifiedAt: string,
  width: number = 1440,
): Promise<{ key: string; bytes: number } | null> {
  const thumUrl =
    "https://image.thum.io/get/width/" + width +
    "/crop/2400/png/" + pageUrl;
  const imgRes = await fetch(thumUrl);
  if (!imgRes.ok) {
    console.warn(`[insights] thum.io failed ${imgRes.status} for ${pageUrl}`);
    return null;
  }
  const buf = await imgRes.arrayBuffer();
  const bytes = buf.byteLength;
  const captureIso = new Date().toISOString();
  const key = `insights:snap:${pageId}:${captureIso}`;
  await env.DIAL_STATE.put(key, buf, {
    expirationTtl: 60 * 60 * 24 * 90,
    metadata: { pageId, pageUrl, modifiedAt, capturedAt: captureIso, width, bytes },
  });
  const timelineKey = `insights:timeline:${pageId}`;
  const timelineRaw = await env.DIAL_STATE.get(timelineKey);
  const timeline: any[] = timelineRaw ? JSON.parse(timelineRaw) : [];
  timeline.unshift({ key, capturedAt: captureIso, modifiedAt, pageUrl, width, bytes });
  await env.DIAL_STATE.put(
    timelineKey,
    JSON.stringify(timeline.slice(0, 50)),
    { expirationTtl: 60 * 60 * 24 * 180 }
  );
  return { key, bytes };
}

// Daily end-of-day baseline — captures EVERY tracked page once per day,
// regardless of whether WP modified timestamp changed. This guarantees a
// permanent daily snapshot record even on pages that don't get edited often,
// so when we look at the timeline weeks later we have continuous coverage.
// Dedupe: if today's daily key was already set, skip (prevents double-runs
// if cron fires twice due to CF retry).
async function dailyInsightsBaseline(env: Env): Promise<void> {
  const today = new Date().toISOString().slice(0, 10);  // YYYY-MM-DD UTC
  const sentinelKey = `insights:daily_done:${today}`;
  const already = await env.DIAL_STATE.get(sentinelKey);
  if (already) {
    console.log(`[daily-baseline] already ran today (${today}) — skipping`);
    return;
  }
  console.log(`[daily-baseline] starting for ${today} — ${INSIGHTS_TRACKED_PAGES.length} pages`);
  let captured = 0;
  let failed = 0;
  for (const { id, label } of INSIGHTS_TRACKED_PAGES) {
    try {
      const meta = await fetchWpPageMeta(env, id);
      if (!meta) {
        console.warn(`[daily-baseline] WP meta fetch failed for ${label} (id=${id})`);
        failed++;
        continue;
      }
      const result = await captureAndStoreSnapshot(env, id, meta.link, meta.modified);
      if (result) {
        captured++;
        console.log(`[daily-baseline] captured ${label}: ${result.bytes} bytes`);
      } else {
        failed++;
      }
      // Also bump last-known modified so the change-poll doesn't immediately
      // re-capture on its next tick
      await env.DIAL_STATE.put(`insights:lastmod:${id}`, meta.modified, {
        expirationTtl: 60 * 60 * 24 * 180,
      });
    } catch (e: any) {
      console.warn(`[daily-baseline] failed ${label}: ${e?.message || e}`);
      failed++;
    }
  }
  // Sentinel TTL = 25h (longer than 24 so we don't accidentally re-fire if cron is slow)
  await env.DIAL_STATE.put(sentinelKey, new Date().toISOString(), {
    expirationTtl: 60 * 60 * 25,
  });
  console.log(`[daily-baseline] done: ${captured} captured, ${failed} failed`);
}

async function pollInsightsForChanges(env: Env): Promise<void> {
  for (const { id, label } of INSIGHTS_TRACKED_PAGES) {
    try {
      const meta = await fetchWpPageMeta(env, id);
      if (!meta) continue;
      const lastModKey = `insights:lastmod:${id}`;
      const lastMod = await env.DIAL_STATE.get(lastModKey);
      if (lastMod === meta.modified) continue;
      console.log(`[insights] change detected: ${label} (id=${id}) was=${lastMod || "(never)"} now=${meta.modified}`);
      const result = await captureAndStoreSnapshot(env, id, meta.link, meta.modified);
      if (result) {
        await env.DIAL_STATE.put(lastModKey, meta.modified, {
          expirationTtl: 60 * 60 * 24 * 180,
        });
        console.log(`[insights] captured ${label}: ${result.bytes} bytes`);
      }
    } catch (e) {
      console.warn(`[insights] failed for ${label}: ${e}`);
    }
  }
}

async function handleInsightsListPages(env: Env): Promise<Response> {
  // Parallel fetch: was sequential which timed out at ~16 pages × 500ms each.
  // Each page is independent — fan out, fan in. Total wall time ≈ slowest
  // single call instead of sum of all calls.
  const settled = await Promise.allSettled(
    INSIGHTS_TRACKED_PAGES.map(async ({ id, label }) => {
      const [meta, timelineRaw] = await Promise.all([
        fetchWpPageMeta(env, id),
        env.DIAL_STATE.get(`insights:timeline:${id}`),
      ]);
      if (!meta) return { id, label, error: "wp_fetch_failed" };
      const timeline = timelineRaw ? JSON.parse(timelineRaw) : [];
      const latest = timeline[0] || null;
      const claritySlug = encodeURIComponent(meta.link);
      return {
        id, label,
        title: meta.title,
        slug: meta.slug,
        link: meta.link,
        modified: meta.modified,
        snapshotCount: timeline.length,
        latestKey: latest?.key,
        latestCapturedAt: latest?.capturedAt,
        clarityHeatmapUrl: `https://clarity.microsoft.com/projects/view/${CLARITY_PROJECT_ID}/heatmaps?date=Last+7+days&Page=${claritySlug}`,
        clarityRecordingsUrl: `https://clarity.microsoft.com/projects/view/${CLARITY_PROJECT_ID}/recordings?date=Last+7+days&Page=${claritySlug}`,
      };
    })
  );

  const result = settled.map((s, i) => {
    const tracked = INSIGHTS_TRACKED_PAGES[i];
    return s.status === "fulfilled"
      ? s.value
      : { id: tracked.id, label: tracked.label, error: String((s as any).reason?.message || (s as any).reason) };
  });

  return new Response(JSON.stringify({ pages: result }, null, 2), {
    status: 200,
    headers: { "content-type": "application/json", "cache-control": "no-store" },
  });
}

